using System.Runtime.Versioning;
using Microsoft.Win32;

namespace StealthDesk.Agent.Windows.Service;

/// <summary>
/// The <c>SoftwareSASGeneration</c> policy, which lets a program raise the secure attention sequence (Ctrl+Alt+Del) so
/// a remote viewer can reach the sign-in and UAC screens. Install turns it on; uninstall turns it off again.
/// </summary>
[SupportedOSPlatform("windows")]
public static class SecureAttention
{
  private const string PolicyKey = @"SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System";
  private const string ValueName = "SoftwareSASGeneration";

  // 3: both services and ease-of-access applications may generate it.
  private const int Both = 3;

  /// <summary>Allows the secure attention sequence to be generated by software.</summary>
  public static void Enable()
  {
    using var key = Registry.LocalMachine.CreateSubKey(PolicyKey, writable: true);
    key.SetValue(ValueName, Both, RegistryValueKind.DWord);
  }

  /// <summary>Stops allowing it, leaving the policy as it was before install.</summary>
  public static void Disable()
  {
    using var key = Registry.LocalMachine.OpenSubKey(PolicyKey, writable: true);
    key?.DeleteValue(ValueName, throwOnMissingValue: false);
  }
}
